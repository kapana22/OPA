export function Icon({
  name,
  size = 20,
  color,
  weight,
  style,
}: {
  name: string;
  size?: number;
  color?: string;
  /** ნაგულისხმევს ცვლის — მაგ. დიდ დეკორატიულ ხატულაზე `duotone`. */
  weight?: IconWeight;
  style?: StyleProp<ViewStyle>;
  /** ძველი პროპები — ხატულა ყოველთვის დეკორატიულია, წამკითხველი მას არ კითხულობს. */
  accessible?: boolean;
}) {
  const entry = MAP[name];
  if (!entry) {
    if (__DEV__) console.warn(`[Icon] უცნობი ხატულა: ${name}`);
    return null;
  }
  const [Glyph, defaultWeight] = entry;
  return (
    <Glyph
      size={size}
      color={color}
      weight={weight ?? defaultWeight}
      style={style as never}
    />
  );
}

